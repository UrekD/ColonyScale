using System;
using System.Collections.Generic;
using System.IO;
using System.Linq;
using System.Reflection;
using HarmonyLib;

namespace ColonyScale
{
    /// <summary>Indirection so the offline pipeline (plain .NET, no Unity) can run this code.</summary>
    public static class CSLog
    {
        public static Action<string> MessageSink = Console.WriteLine;
        public static Action<string> WarningSink = Console.WriteLine;
        public static Action<string> ErrorSink = Console.Error.WriteLine;

        public static void Message(string text) => MessageSink("[ColonyScale] " + text);
        public static void Warning(string text) => WarningSink("[ColonyScale] " + text);
        public static void Error(string text) => ErrorSink("[ColonyScale] " + text);
    }

    /// <summary>
    /// Expected IL fingerprints, one line per patch target: optimizationId, memberId, hash. The header records the game
    /// and the Harmony version they were taken with (Harmony's IL reader produces the instructions that are hashed).
    /// </summary>
    public sealed class FingerprintStore
    {
        public const string FileName = "Fingerprints.tsv";
        public string GameVersion = "";
        public string HarmonyVersion = "";
        private readonly Dictionary<string, string> expected = new Dictionary<string, string>();

        public static string Key(string optimizationId, string memberId) => optimizationId + "\t" + memberId;

        public bool TryGet(string optimizationId, string memberId, out string hash) =>
            expected.TryGetValue(Key(optimizationId, memberId), out hash);

        public void Set(string optimizationId, string memberId, string hash) => expected[Key(optimizationId, memberId)] = hash;

        public static FingerprintStore Load(string path)
        {
            var store = new FingerprintStore();
            if (!File.Exists(path)) return store;
            foreach (var raw in File.ReadAllLines(path))
            {
                var line = raw.TrimEnd('\r');
                if (line.StartsWith("# game\t")) { store.GameVersion = line.Substring(7); continue; }
                if (line.StartsWith("# harmony\t")) { store.HarmonyVersion = line.Substring(10); continue; }
                if (line.Length == 0 || line[0] == '#') continue;
                var parts = line.Split('\t');
                if (parts.Length == 3) store.Set(parts[0], parts[1], parts[2]);
            }
            return store;
        }

        public void Save(string path)
        {
            var lines = new List<string>
            {
                "# Expected IL fingerprints of every patched game method. Generated by `make fingerprints`; do not edit.",
                "# game\t" + GameVersion,
                "# harmony\t" + HarmonyVersion,
            };
            lines.AddRange(expected.OrderBy(kv => kv.Key, StringComparer.Ordinal).Select(kv => kv.Key + "\t" + kv.Value));
            File.WriteAllLines(path, lines);
        }
    }

    public static class PatchManager
    {
        public const string HarmonyId = "UrekD.ColonyScale";

        private static Harmony harmony;
        public static List<Optimization> All { get; private set; } = new List<Optimization>();
        public static FingerprintStore Fingerprints { get; private set; } = new FingerprintStore();

        /// <summary>Set by the mod to ModsConfig.IsActive; the offline pipeline leaves it returning false.</summary>
        public static Func<string, bool> IsModActive = _ => false;

        /// <summary>When true, optimizations whose target IL changed are applied anyway (user override).</summary>
        public static bool TrustChangedTargets;

        /// <summary>
        /// Oldest Harmony this mod runs on. It is compiled against 2.4 and the foreign-patch checks read the inner
        /// prefix/postfix collections that 2.4 introduced; older versions are refused at startup.
        /// </summary>
        public static readonly Version MinHarmonyVersion = new Version(2, 4, 0, 0);

        /// <summary>The Harmony actually loaded (the Harmony mod's copy in game, Lib.Harmony offline).</summary>
        public static Version HarmonyVersion => typeof(Harmony).Assembly.GetName().Version;

        /// <summary>Null when Harmony <paramref name="version"/> is supported, else the message to show.</summary>
        public static string HarmonyVersionProblem(Version version) =>
            version >= MinHarmonyVersion ? null
                : $"Harmony {version} is too old: Colony Scale needs Harmony {MinHarmonyVersion.ToString(2)} or newer. Update the Harmony mod; until then every optimization stays off.";

        public static void Init(FingerprintStore fingerprints)
        {
            harmony = new Harmony(HarmonyId);
            Fingerprints = fingerprints ?? new FingerprintStore();
            All = OptimizationRegistry.Discover();
        }

        /// <summary>
        /// Applies the optimization if every check passes. On an already active optimization the checks are run
        /// again (another mod may have patched something since) and it is turned off if one now fails.
        /// An unexpected exception (a check, a patch method or OnEnabled throwing) costs only this optimization.
        /// </summary>
        public static bool TryEnable(Optimization opt)
        {
            if (opt is UnavailableOptimization) return false; // stays Failed with its creation error
            try { return TryEnableChecked(opt); }
            catch (Exception e)
            {
                string reason = "unexpected error: " + (e.InnerException ?? e).Message;
                CSLog.Error($"{opt.Label}: {reason}\n{e}");
                bool removed;
                try { removed = RemovePatches(opt); }
                catch (Exception) { removed = false; }
                if (!removed)
                    return SetState(opt, OptimizationState.DisableFailed, reason + "; some of its patches may still be installed, restart the game");
                try { opt.ClearCaches(); }
                catch (Exception) { }
                return SetState(opt, OptimizationState.Failed, reason);
            }
        }

        private static bool TryEnableChecked(Optimization opt)
        {
            if (!opt.IsActive && opt.applied.Count > 0)
                return SetState(opt, OptimizationState.DisableFailed,
                    "an earlier disable left patches in place; not re-applying until the game is restarted");

            var failure = Check(opt, out var patches);
            if (failure != null)
            {
                if (!opt.IsActive) return SetState(opt, failure.Value.state, failure.Value.reason);
                CSLog.Warning($"{opt.Label}: turning off, {failure.Value.reason}");
                Disable(opt, failure.Value.state, failure.Value.reason);
                return false;
            }
            if (opt.IsActive) return true;

            try
            {
                foreach (var p in patches)
                {
                    harmony.Patch(p.Target, p.Prefix, p.Postfix, p.Transpiler);
                    opt.applied.Add(p);
                }
            }
            catch (Exception e)
            {
                string reason = e.InnerException?.Message ?? e.Message;
                if (!RemovePatches(opt))
                    return SetState(opt, OptimizationState.DisableFailed, "failed to apply (" + reason + ") and failed to remove the partial patches");
                opt.ClearCaches();
                return SetState(opt, OptimizationState.Failed, reason);
            }

            opt.OnEnabled();
            return SetState(opt, OptimizationState.Active, null);
        }

        /// <summary>
        /// Re-runs <see cref="TryEnable"/> on every active optimization; for patches other mods install after
        /// startup (static constructors, deferred callbacks, game start). Returns how many were turned off.
        /// </summary>
        public static int RevalidateActive(string when)
        {
            int turnedOff = 0;
            foreach (var opt in All.Where(o => o.IsActive).ToList())
                if (!TryEnable(opt)) turnedOff++;
            if (turnedOff > 0)
                CSLog.Warning($"{turnedOff} optimization(s) turned off {when}; see the mod settings for the reason");
            return turnedOff;
        }

        /// <summary>Null when the optimization may be (or stay) applied, else the state to report and why.</summary>
        private static (OptimizationState state, string reason)? Check(Optimization opt, out List<PatchSpec> patches)
        {
            patches = null;
            string conflictMod = opt.IncompatiblePackageIds.FirstOrDefault(IsModActive);
            if (conflictMod != null)
                return (OptimizationState.DisabledConflict, "mod already covers this: " + conflictMod);

            try { patches = opt.GetPatches().ToList(); }
            catch (Exception e) { return (OptimizationState.Failed, "target not found: " + e.Message); }

            List<MethodBase> depends;
            try { depends = opt.DependsOn.ToList(); }
            catch (Exception e) { return (OptimizationState.Failed, "dependency not found: " + e.Message); }
            if (depends.Any(m => m == null)) return (OptimizationState.Failed, "dependency not found");

            string invalid = patches.Select(p => p.Problem()).FirstOrDefault(r => r != null);
            if (invalid != null) return (OptimizationState.Failed, invalid);

            foreach (var method in PatchSpec.Fingerprinted(patches, depends))
            {
                string reason = CheckFingerprint(opt, method);
                if (reason != null && !TrustChangedTargets)
                    return (OptimizationState.DisabledTargetChanged, reason);
            }
            foreach (var p in patches)
            {
                string reason = p.ReplacesOriginal ? ForeignPatchesOnReplaced(p) : null;
                if (reason != null) return (OptimizationState.DisabledConflict, reason);
            }
            foreach (var method in depends)
            {
                string reason = ForeignPatches(method);
                if (reason != null) return (OptimizationState.DisabledConflict, reason);
            }
            return null;
        }

        /// <summary>
        /// Removes the patches and reports the new state. Returns false (state <see cref="OptimizationState.DisableFailed"/>)
        /// when Harmony still holds one of our patches; caches are then kept, since the patched code may still use them.
        /// </summary>
        public static bool Disable(Optimization opt, OptimizationState newState, string reason = null)
        {
            if (!RemovePatches(opt))
            {
                SetState(opt, OptimizationState.DisableFailed,
                    "could not remove its patches from " + string.Join(", ", opt.applied.Select(p => p.Target.DeclaringType?.Name + "." + p.Target.Name).Distinct()) +
                    "; it may still be running, restart the game");
                return false;
            }
            opt.ClearCaches();
            SetState(opt, newState, reason);
            return true;
        }

        /// <summary>Unpatches every applied spec; specs Harmony still holds a patch of stay in <c>applied</c>.</summary>
        private static bool RemovePatches(Optimization opt)
        {
            foreach (var p in opt.applied.ToList())
            {
                foreach (var m in p.PatchMethods())
                {
                    try { harmony.Unpatch(p.Target, m); }
                    catch (Exception e) { CSLog.Error($"unpatching {opt.Id} from {p.Target.Name} failed: {e.InnerException?.Message ?? e.Message}"); }
                }
                if (!HasAnyPatchOf(p)) opt.applied.Remove(p);
            }
            return opt.applied.Count == 0;
        }

        /// <summary>True when Harmony's actual patch state still contains one of this spec's patch methods.</summary>
        public static bool HasAnyPatchOf(PatchSpec p) => p.PatchMethods().Any(m => OwnPatches(p.Target).Any(x => x.PatchMethod == m));

        /// <summary>True when Harmony's actual patch state contains every patch method of every spec.</summary>
        public static bool HasAllPatchesOf(Optimization opt) =>
            opt.applied.Count > 0 && opt.applied.All(p => p.PatchMethods().All(m => OwnPatches(p.Target).Any(x => x.PatchMethod == m)));

        /// <summary>True when Harmony holds none of this optimization's patches.</summary>
        public static bool HasNoPatchesOf(Optimization opt)
        {
            if (opt.applied.Count > 0) return false;
            List<PatchSpec> specs;
            try { specs = opt.GetPatches().ToList(); }
            catch (Exception) { return true; } // unresolvable targets cannot carry our patches
            return !specs.Any(HasAnyPatchOf);
        }

        private static IEnumerable<Patch> OwnPatches(MethodBase method) => AllPatches(Harmony.GetPatchInfo(method)).Where(x => x.owner == HarmonyId);

        /// <summary>Every patch category Harmony 2.4 supports.</summary>
        private static IEnumerable<Patch> AllPatches(Patches info) =>
            info == null ? Enumerable.Empty<Patch>() :
            info.Prefixes.Concat(info.Postfixes).Concat(info.Transpilers).Concat(info.Finalizers)
                .Concat(InnerPrefixes(info)).Concat(InnerPostfixes(info));

        // Read by reflection so no method here binds to members older Harmony versions lack; startup refuses those
        // versions anyway (MinHarmonyVersion), this only keeps the failure path itself from throwing.
        private static readonly MethodInfo InnerPrefixesGetter = AccessTools.PropertyGetter(typeof(Patches), "InnerPrefixes");
        private static readonly MethodInfo InnerPostfixesGetter = AccessTools.PropertyGetter(typeof(Patches), "InnerPostfixes");

        private static IEnumerable<Patch> InnerPrefixes(Patches info) =>
            (IEnumerable<Patch>)InnerPrefixesGetter?.Invoke(info, null) ?? Enumerable.Empty<Patch>();

        private static IEnumerable<Patch> InnerPostfixes(Patches info) =>
            (IEnumerable<Patch>)InnerPostfixesGetter?.Invoke(info, null) ?? Enumerable.Empty<Patch>();

        private static readonly Dictionary<MethodBase, string> computedFingerprints = new Dictionary<MethodBase, string>();

        /// <summary>Null when the method's IL matches the recorded fingerprint, else the reason.</summary>
        public static string CheckFingerprint(Optimization opt, MethodBase method)
        {
            string member = ILFingerprint.MemberId(method);
            if (!Fingerprints.TryGet(opt.Id, member, out var expected))
                return "no recorded fingerprint for " + member;
            // Original IL cannot change while the game runs, so each method is hashed once.
            if (!computedFingerprints.TryGetValue(method, out var actual))
            {
                try { actual = ILFingerprint.Compute(method); }
                catch (Exception e) { return "could not read IL of " + member + ": " + e.Message; }
                computedFingerprints[method] = actual;
            }
            return actual == expected ? null : "game code changed: " + member;
        }

        /// <summary>
        /// A method we reason about (DependsOn): any foreign patch of any kind may change what it does, so our
        /// reasoning no longer holds.
        /// </summary>
        private static string ForeignPatches(MethodBase method)
        {
            var owners = AllPatches(Harmony.GetPatchInfo(method)).Select(t => t.owner).Where(o => o != HarmonyId).Distinct().ToList();
            return owners.Count == 0 ? null : "another mod patches " + Describe(method) + ": " + string.Join(", ", owners);
        }

        /// <summary>
        /// A body our prefix replaces (returns false): foreign transpilers and inner prefixes/postfixes act on the
        /// skipped body, and a foreign prefix that can sort after ours is skipped (bool prefixes) or sees the
        /// original never run. Only prefixes with a strictly higher priority and no ordering constraints are
        /// certain to run first; postfixes and finalizers still run and are fine.
        /// </summary>
        private static string ForeignPatchesOnReplaced(PatchSpec spec)
        {
            var info = Harmony.GetPatchInfo(spec.Target);
            if (info == null) return null;
            int ours = spec.Prefix.priority == -1 ? Priority.Normal : spec.Prefix.priority;
            var bodyPatches = info.Transpilers.Concat(InnerPrefixes(info)).Concat(InnerPostfixes(info));
            var latePrefixes = info.Prefixes.Where(x =>
                x.priority <= ours || (x.before != null && x.before.Length > 0) || (x.after != null && x.after.Length > 0));
            var owners = bodyPatches.Concat(latePrefixes).Select(t => t.owner).Where(o => o != HarmonyId).Distinct().ToList();
            return owners.Count == 0 ? null : "another mod patches " + Describe(spec.Target) + ", which this replaces: " + string.Join(", ", owners);
        }

        private static string Describe(MethodBase method) => method.DeclaringType?.Name + "." + method.Name;

        private static bool SetState(Optimization opt, OptimizationState state, string reason)
        {
            opt.State = state;
            opt.StateReason = reason;
            if (state == OptimizationState.DisableFailed)
                CSLog.Error($"{opt.Label} failed to turn off: {reason}");
            else if (state == OptimizationState.Failed || state == OptimizationState.DisabledTargetChanged || state == OptimizationState.DisabledConflict)
                CSLog.Warning($"{opt.Label} is off: {reason}");
            return state == OptimizationState.Active;
        }
    }
}
